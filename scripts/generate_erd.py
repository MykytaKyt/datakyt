"""Generate docs/diagram.md (a Mermaid ER diagram plus column tables) from the models.

Usage:
    python scripts/generate_erd.py           # rewrite docs/diagram.md
    python scripts/generate_erd.py --check   # exit 1 if the file is out of date
"""

import sys
from pathlib import Path

from sqlalchemy import Column, Enum, Table
from sqlalchemy.dialects import postgresql

from datakyt.models import Base

TARGET = Path(__file__).resolve().parent.parent / "docs" / "diagram.md"
DIALECT = postgresql.dialect()  # type: ignore[no-untyped-call]


def column_type(column: Column[object]) -> str:
    if isinstance(column.type, Enum):
        return f"enum {column.type.name}"
    return str(column.type.compile(dialect=DIALECT)).lower()


def keys(table: Table, column: Column[object]) -> str:
    marks = []
    if column.primary_key:
        marks.append("PK")
    if column.foreign_keys:
        marks.append("FK")
    unique_sets = [
        {c.name for c in constraint.columns}
        for constraint in table.constraints
        if constraint.__class__.__name__ == "UniqueConstraint"
    ] + [
        {c.name for c in index.columns}
        for index in table.indexes
        if index.unique and index.dialect_options["postgresql"]["where"] is None
    ]
    if {column.name} in unique_sets:
        marks.append("UK")
    return ",".join(marks)


def render() -> str:
    tables = sorted(Base.metadata.tables.values(), key=lambda t: t.name)
    lines = [
        "# Database schema",
        "",
        "<!-- Generated by scripts/generate_erd.py from datakyt/models. Do not edit by hand;",
        "     run `make erd` after changing the models. -->",
        "",
        "```mermaid",
        "erDiagram",
    ]
    for table in tables:
        for fk in sorted(table.foreign_keys, key=lambda f: f.parent.name):
            parent = fk.column.table.name
            optional = "o" if fk.parent.nullable else "|"
            lines.append(f'    {parent} |{optional}--o{{ {table.name} : "{fk.parent.name}"')
    for table in tables:
        lines.append(f"    {table.name} {{")
        for column in table.columns:
            type_name = column_type(column).replace(" ", "_").replace(",", "_")
            mark = keys(table, column)
            lines.append(f"        {type_name} {column.name}{(' ' + mark) if mark else ''}")
        lines.append("    }")
    lines += ["```", ""]

    for table in tables:
        lines += [f"## {table.name}", "", "| column | type | null | keys | references |"]
        lines.append("| --- | --- | --- | --- | --- |")
        for column in table.columns:
            refs = ", ".join(
                f"{fk.column.table.name}.{fk.column.name} ({fk.ondelete or 'NO ACTION'})"
                for fk in column.foreign_keys
            )
            lines.append(
                f"| {column.name} | {column_type(column)} | {'yes' if column.nullable else 'no'}"
                f" | {keys(table, column)} | {refs} |"
            )
        checks = sorted(
            str(c.sqltext) for c in table.constraints if c.__class__.__name__ == "CheckConstraint"
        )
        partial = sorted(
            f"unique ({', '.join(c.name for c in index.columns)}) where "
            f"{index.dialect_options['postgresql']['where']}"
            for index in table.indexes
            if index.unique and index.dialect_options["postgresql"]["where"] is not None
        )
        if checks or partial:
            lines.append("")
            lines += [f"- check: `{c}`" for c in checks]
            lines += [f"- {p}" for p in partial]
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    content = render()
    if "--check" in sys.argv:
        if not TARGET.exists() or TARGET.read_text("utf-8") != content:
            print(f"{TARGET} is out of date; run `make erd`", file=sys.stderr)
            return 1
        return 0
    TARGET.write_text(content, "utf-8")
    print(f"wrote {TARGET}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
